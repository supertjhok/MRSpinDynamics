"""Geometry-level hardware specs for the experiment facade.

These frozen dataclasses describe transmit/receive coils, the static-field
direction, and where the imaging plane sits in the coil's physical frame.
All geometry is in SI meters (the ``fields`` solvers' convention); the
imaging workflow's ``fov`` stays in its own self-consistent units and is
independent of these specs.

The specs are pure data — solving them into field maps happens in
:mod:`spin_dynamics.experiment.wiring`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Sequence

from spin_dynamics.experiment.serialization import register_serializable
from spin_dynamics.fields.coils import planar_spiral, solenoid

Segment = tuple[Sequence[float], Sequence[float]]

_AXES = ("x", "y", "z")
_PLANES = ("xz", "xy", "yz")


def _as_vec3(value: Any, name: str) -> tuple[float, float, float]:
    vec = tuple(float(v) for v in value)
    if len(vec) != 3:
        raise ValueError(f"{name} must have three components")
    return vec


@register_serializable
@dataclass(frozen=True)
class SolenoidCoil:
    """Solenoid winding, generated by ``fields.coils.solenoid``."""

    radius_m: float
    length_m: float
    turns: int
    center_m: tuple[float, float, float] = (0.0, 0.0, 0.0)
    axis: str = "z"
    n_segments: int = 48

    def __post_init__(self) -> None:
        object.__setattr__(self, "center_m", _as_vec3(self.center_m, "center_m"))
        if self.axis not in _AXES:
            raise ValueError(f"axis must be one of {_AXES}")
        if self.radius_m <= 0 or self.length_m <= 0 or self.turns <= 0:
            raise ValueError("radius_m, length_m, and turns must be positive")

    def segments(self) -> list[Segment]:
        return solenoid(
            radius=self.radius_m,
            length=self.length_m,
            turns=self.turns,
            center=self.center_m,
            axis=self.axis,
            n_segments=self.n_segments,
        )


@register_serializable
@dataclass(frozen=True)
class PlanarSpiralCoil:
    """Planar spiral (surface) coil, generated by ``fields.coils.planar_spiral``."""

    r_inner_m: float
    r_outer_m: float
    turns: int
    center_m: tuple[float, float, float] = (0.0, 0.0, 0.0)
    axis: str = "z"
    n_points: int = 400

    def __post_init__(self) -> None:
        object.__setattr__(self, "center_m", _as_vec3(self.center_m, "center_m"))
        if self.axis not in _AXES:
            raise ValueError(f"axis must be one of {_AXES}")
        if self.r_inner_m <= 0 or self.r_outer_m <= self.r_inner_m or self.turns <= 0:
            raise ValueError("require 0 < r_inner_m < r_outer_m and positive turns")

    def segments(self) -> list[Segment]:
        return planar_spiral(
            r_inner=self.r_inner_m,
            r_outer=self.r_outer_m,
            turns=self.turns,
            center=self.center_m,
            axis=self.axis,
            n_points=self.n_points,
        )


COIL_GEOMETRY_TYPES: tuple[type, ...] = (SolenoidCoil, PlanarSpiralCoil)


def _check_geometry(geometry: Any) -> None:
    if not isinstance(geometry, COIL_GEOMETRY_TYPES):
        names = ", ".join(cls.__name__ for cls in COIL_GEOMETRY_TYPES)
        raise ValueError(f"coil geometry must be one of: {names}")


@register_serializable
@dataclass(frozen=True)
class TxCoil:
    """Transmit coil: geometry plus drive current for the Biot-Savart solve.

    The solved transverse-B1 map is normalized to a rho-weighted mean of one
    (transmit calibration at the sample), so ``current_amps`` only matters for
    the spatial *shape* through nothing — it is kept for forward compatibility
    with absolute-field workflows.
    """

    geometry: Any
    current_amps: float = 1.0

    def __post_init__(self) -> None:
        _check_geometry(self.geometry)
        if self.current_amps <= 0:
            raise ValueError("current_amps must be positive")


@register_serializable
@dataclass(frozen=True)
class RxCoil:
    """Receive coil; sensitivity is solved by reciprocity with unit current."""

    geometry: Any

    def __post_init__(self) -> None:
        _check_geometry(self.geometry)


@register_serializable
@dataclass(frozen=True)
class UniformB0:
    """Uniform static field: defines the direction B1 is projected against."""

    direction: tuple[float, float, float] = (0.0, 0.0, 1.0)

    def __post_init__(self) -> None:
        direction = _as_vec3(self.direction, "direction")
        norm = sum(c * c for c in direction) ** 0.5
        if norm <= 0:
            raise ValueError("direction must be a non-zero vector")
        object.__setattr__(self, "direction", direction)


@register_serializable
@dataclass(frozen=True)
class ImagingPlane:
    """Physical placement of the 2-D phantom grid in the coil frame.

    ``plane="xz"`` maps phantom index axis 0 to spatial x and axis 1 to
    spatial z (matching the imaging workflows' ``del_wx``/``del_wz`` axes),
    with the remaining coordinate fixed by ``center_m``.
    """

    extent_m: tuple[float, float] = (0.02, 0.02)
    plane: str = "xz"
    center_m: tuple[float, float, float] = (0.0, 0.0, 0.0)

    def __post_init__(self) -> None:
        extent = tuple(float(v) for v in self.extent_m)
        if len(extent) != 2 or any(v <= 0 for v in extent):
            raise ValueError("extent_m must contain two positive lengths")
        object.__setattr__(self, "extent_m", extent)
        if self.plane not in _PLANES:
            raise ValueError(f"plane must be one of {_PLANES}")
        object.__setattr__(self, "center_m", _as_vec3(self.center_m, "center_m"))
